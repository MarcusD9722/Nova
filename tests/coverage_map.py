"""Layer 1 of the test program: which functions does no test ever run?

Runs every offline suite - exactly the `tests/test_*.py` set that
`run_tests.ps1` runs - under coverage.py, with branch coverage and child
processes included, and then maps the result onto FUNCTIONS. A line
percentage says nothing about which behaviour is unproven; a list of the
functions nothing ever calls does.

    venv\\Scripts\\python.exe tests\\coverage_map.py run [regex]   measure
    venv\\Scripts\\python.exe tests\\coverage_map.py report        map it

It lives in `tests/` with the other scripts that drive suites (the soak, the
mutation runners), not in `tools/`: it sets the test harness's own
`NOVA_IT_WATCHDOG_S`, and `tools/` is scanned by test_settings_p04 as Nova
code, where every NOVA_* name must be a cataloged Nova setting.

`run` with a regex measures only the matching suites (same matching as
`run_tests.ps1 <filter>`); add `--append` to add them to an earlier run
instead of starting over.

Everything it writes goes to `coverage_map/` (gitignored):

    data/           raw coverage data, one file per process
    suites.json     every suite's exit status and duration under coverage
    functions.json  one record per function: statements, executed, suites
    handlers.json   every `except` block, classified by whether it is heard
    REPORT.md       the summary and the gap lists
    html/           line-by-line report; shows which suite ran each line

WHAT "RUN" MEANS, PRECISELY

* A function is RUN when at least one statement of its OWN body executed.
  The `def` line does not count: it executes at import whether or not
  anything ever calls the function. A nested function's body belongs to the
  nested function, not to its parent.
* RUN IS NOT TESTED. Coverage says a line executed, not that anything
  checked what it did. This map finds the code no test can possibly be
  proving yet, because nothing reaches it. Whether the tests that DO reach a
  function would notice it breaking is layer 2's question, answered with
  mutation checks, not here.
* A suite that fails under coverage still contributes what it executed, and
  it is listed in the report, so a gap caused by a crashed suite is not
  mistaken for a gap in the tests.

AN `except` BLOCK IS "QUIET" when it neither re-raises nor calls anything
that looks like a log method or print. Quiet is not automatically wrong - a
guard that turns a bad value into a refusal is the guard working (audit
M12) - but a quiet block is where a failure can disappear, which is how deep
mode's planner and critic failed for months without one line of evidence.
Whether each quiet block was REACHED by any suite is recorded too: a quiet
block a test reached means an error was swallowed while that test ran.
"""
from __future__ import annotations

import argparse
import ast
import datetime as _dt
import json
import os
import re
import shutil
import subprocess
import sys
import time
from collections import defaultdict
from pathlib import Path
from typing import Any, Iterable, Iterator, Mapping

REPO = Path(__file__).resolve().parent.parent
PY = REPO / "venv" / "Scripts" / "python.exe"
OUT = REPO / "coverage_map"
DATA = OUT / "data"
RC = OUT / "coveragerc"

#: Measured trees. The program is about the first three; the other two are
#: measured as well, because a gap there is still a gap.
SOURCES = ("core", "memory", "backend", "plugins", "services")
FOCUS = ("core", "memory", "backend")

#: Per-suite ceiling. Tracing makes every suite slower, and a suite killed by
#: the harness watchdog dies in C-level `_exit` and saves NO data, so the
#: watchdog is raised for this run and this outer limit catches a real hang.
SUITE_TIMEOUT_S = 3600

#: Method names that count as "this failure was told to someone", by level.
_HEARD_LEVELS = {"debug": 1, "info": 2, "msg": 2, "warning": 3, "warn": 3,
                 "error": 4, "exception": 4, "critical": 4}
_LEVEL_NAMES = {0: "quiet", 1: "logs-debug", 2: "logs-info",
                3: "logs-warning", 4: "logs-error"}

#: FastAPI decorators that make a function an HTTP/WebSocket endpoint.
_ROUTE_METHODS = frozenset({"get", "post", "put", "delete", "patch", "head",
                            "options", "websocket", "api_route"})


# ── run ──────────────────────────────────────────────────────────────────────

def write_rc() -> None:
    OUT.mkdir(exist_ok=True)
    sources = "\n".join(f"    {REPO / s}" for s in SOURCES)
    RC.write_text(
        "# Generated by tests/coverage_map.py - edits here are overwritten.\n"
        "[run]\n"
        "branch = True\n"
        "parallel = True\n"
        f"data_file = {DATA / '.coverage'}\n"
        # Absolute paths: a child process may run with a different cwd, and a
        # relative source would then silently measure nothing.
        f"source =\n{sources}\n"
        # subprocess: measure child interpreters too (the restart suites run
        # most of their work in one). _exit: save data before os._exit, which
        # the crash-boundary suites use to die on purpose.
        "patch =\n    subprocess\n    _exit\n"
        "disable_warnings =\n    no-data-collected\n    module-not-imported\n"
        "omit =\n    */__pycache__/*\n"
        "\n[report]\nskip_empty = True\n",
        encoding="utf-8",
    )


def _text(blob: Any) -> str:
    if blob is None:
        return ""
    if isinstance(blob, bytes):
        return blob.decode("utf-8", errors="replace")
    return str(blob)


def cmd_run(pattern: str | None, append: bool) -> int:
    if not PY.exists():
        print(f"venv python not found: {PY}")
        return 2
    try:
        import coverage  # noqa: F401
    except ImportError:
        print("coverage is not installed: venv\\Scripts\\python.exe -m pip "
              "install -r requirements-dev.txt")
        return 2
    if DATA.exists() and not append:
        shutil.rmtree(DATA)
    DATA.mkdir(parents=True, exist_ok=True)
    write_rc()

    suites = sorted((REPO / "tests").glob("test_*.py"))
    if pattern:
        rx = re.compile(pattern)
        suites = [s for s in suites if rx.search(s.name)]
    if not suites:
        print("no suites match")
        return 2

    env = dict(os.environ)
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONPATH"] = str(REPO)
    env["NOVA_IT_WATCHDOG_S"] = str(SUITE_TIMEOUT_S)

    results_path = OUT / "suites.json"
    results: list[dict[str, Any]] = []
    if append and results_path.exists():
        names = {s.name for s in suites}
        results = [r for r in json.loads(results_path.read_text(encoding="utf-8"))
                   if r["suite"] not in names]

    t_all = time.perf_counter()
    for i, suite in enumerate(suites, 1):
        cmd = [str(PY), "-m", "coverage", "run", f"--rcfile={RC}",
               f"--context={suite.stem}", str(suite)]
        t0 = time.perf_counter()
        try:
            proc = subprocess.run(cmd, cwd=REPO, env=env, capture_output=True,
                                  encoding="utf-8", errors="replace",
                                  timeout=SUITE_TIMEOUT_S + 60)
            code: int | None = proc.returncode
            out = _text(proc.stdout) + _text(proc.stderr)
        except subprocess.TimeoutExpired as exc:
            code = None
            out = _text(exc.stdout) + _text(exc.stderr)
        elapsed = time.perf_counter() - t0
        status = "pass" if code == 0 else ("timeout" if code is None else "fail")
        rec: dict[str, Any] = {"suite": suite.name, "status": status,
                               "exit": code, "seconds": round(elapsed, 1)}
        if status != "pass":
            lines = out.splitlines()
            hits = [ln for ln in lines if re.search(r"FAIL|Error|Traceback", ln)]
            rec["output"] = (hits[:30] + ["..."] + lines[-30:]) if hits else lines[-40:]
        results.append(rec)
        # Written after EVERY suite, so an interrupted run keeps what it measured.
        results_path.write_text(json.dumps(results, indent=1), encoding="utf-8")
        print(f"[{i:3}/{len(suites)}] {status:7} {elapsed:7.1f}s  {suite.name}",
              flush=True)

    total = time.perf_counter() - t_all
    bad = [r for r in results if r["status"] != "pass"]
    print(f"\n{len(results) - len(bad)}/{len(results)} suites passed under "
          f"coverage; this run took {total / 60:.1f} min")
    for r in bad:
        print(f"  {r['status'].upper()}: {r['suite']}")
    return 1 if bad else 0


# ── mapping lines onto functions ─────────────────────────────────────────────

def iter_functions(tree: ast.AST) -> Iterator[tuple[ast.AST, str, bool]]:
    """(node, qualified name, is_method) for every def, nested ones included."""
    def visit(node: ast.AST, prefix: str, in_class: bool):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                qual = f"{prefix}{child.name}"
                yield child, qual, in_class
                yield from visit(child, qual + ".<locals>.", False)
            elif isinstance(child, ast.ClassDef):
                yield from visit(child, f"{prefix}{child.name}.", True)
            else:
                yield from visit(child, prefix, in_class)
    yield from visit(tree, "", False)


def own_lines(fn: ast.AST) -> set[int]:
    """Lines of `fn`'s own body: nested function BODIES belong to them.

    A nested `def` LINE stays with the parent - it executes when the parent
    runs - and so does a nested class body, which runs at definition.
    """
    start, end = fn.body[0].lineno, fn.end_lineno or fn.body[-1].lineno
    lines = set(range(start, end + 1))
    stack = list(ast.iter_child_nodes(fn))
    while stack:
        node = stack.pop()
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            lines -= set(range(node.body[0].lineno, (node.end_lineno or 0) + 1))
            continue
        stack.extend(ast.iter_child_nodes(node))
    return lines


def route_of(fn: ast.AST) -> str | None:
    """'POST /chat' for a FastAPI endpoint, else None."""
    for dec in getattr(fn, "decorator_list", []):
        if (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute)
                and dec.func.attr in _ROUTE_METHODS):
            path = ""
            if dec.args and isinstance(dec.args[0], ast.Constant):
                path = str(dec.args[0].value)
            return f"{dec.func.attr.upper()} {path}".strip()
    return None


#: Exceptions that mean "there is nothing more", not that something failed:
#: an empty queue, the end of an iterator. Any plain exit from the handler is
#: control flow.
_END_OF_DATA = frozenset({"QueueEmpty", "Empty", "StopIteration", "StopAsyncIteration"})
#: A timeout is control flow ONLY as a poll tick inside a loop (`continue` /
#: `break`). `except TimeoutError: return None` around a network call is a
#: failure being swallowed, and stays "quiet". QueueFull is not on either list:
#: dropping an item because a queue is full is silent data loss. Nor is
#: CancelledError - swallowing it is how shutdown once stopped halfway (U10).
_POLL_TIMEOUT = frozenset({"TimeoutError"})


def _caught_names(handler: ast.ExceptHandler) -> set[str]:
    if handler.type is None:
        return set()
    nodes = handler.type.elts if isinstance(handler.type, ast.Tuple) else [handler.type]
    names = set()
    for n in nodes:
        if isinstance(n, ast.Attribute):
            names.add(n.attr)
        elif isinstance(n, ast.Name):
            names.add(n.id)
    return names


def function_record(node: ast.AST, qual: str, is_method: bool, rel: str,
                    stmts: set[int], executed: set[int],
                    contexts: dict[int, list[str]],
                    missing_br: list[tuple[int, int]],
                    taken_br: list[tuple[int, int]]) -> dict[str, Any]:
    """One function's coverage, from its OWN body lines only."""
    mine = own_lines(node)
    own_st = stmts & mine
    ran = own_st & executed
    return {
        "file": rel, "name": qual, "line": node.lineno,
        "method": is_method,
        "private": qual.split(".")[-1].startswith("_"),
        "async": isinstance(node, ast.AsyncFunctionDef),
        "route": route_of(node),
        "statements": len(own_st), "executed": len(ran),
        "branches": sum(1 for a, _b in missing_br + taken_br if a in mine),
        "branches_missed": sum(1 for a, _b in missing_br if a in mine),
        "status": ("empty" if not own_st else "never" if not ran
                   else "full" if ran == own_st else "partial"),
        "suites": sorted({(c or "(subprocess)") for ln in ran
                          for c in contexts.get(ln, [])}),
    }


def _call_level(call: ast.Call, helpers: Mapping[str, int]) -> int:
    """How loudly one call tells someone: a log method, print, or a log helper."""
    func = call.func
    if isinstance(func, ast.Attribute):
        return max(_HEARD_LEVELS.get(func.attr, 0), helpers.get(func.attr, 0))
    if isinstance(func, ast.Name):
        if func.id == "print":
            return 2
        return helpers.get(func.id, 0)
    return 0


def _only_logs(body: list[ast.stmt]) -> int:
    """The level a body logs at when logging is ALL it does; 0 otherwise.

    A docstring is skipped, and a `try` counts when its body only logs: its
    handlers are the helper's own last resort (log_worker_error falls back
    to stderr, then to nothing). Anything else - an assignment, a counter, a
    return - means the function does real work and merely logs on the way,
    so a call to it does not prove the failure was told to anyone.
    """
    levels: list[int] = []
    for st in body:
        if (isinstance(st, ast.Expr) and isinstance(st.value, ast.Constant)
                and isinstance(st.value.value, str)):
            continue
        if isinstance(st, ast.Expr) and isinstance(st.value, ast.Call):
            lv = _call_level(st.value, {})
        elif isinstance(st, ast.Try) and not st.orelse and not st.finalbody:
            lv = _only_logs(st.body)
        else:
            return 0
        if not lv:
            return 0
        levels.append(lv)
    return min(levels) if levels else 0


def collect_log_helpers(trees: Iterable[ast.AST]) -> dict[str, int]:
    """Functions whose whole job is to log, by name -> the level they log at.

    A handler that calls `log_worker_error(logger, "x", e)` logs at error
    level even though no `.error(` appears in it. Calls are matched by bare
    name, so a name counts only if EVERY function of that name is a pure
    logger, at the lowest level any of them logs at; one same-named function
    that does something else and the name is not trusted at all.
    """
    seen: dict[str, list[int]] = defaultdict(list)
    for tree in trees:
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                seen[node.name].append(_only_logs(node.body))
    return {name: min(lvls) for name, lvls in seen.items() if min(lvls) > 0}


def classify_handler(handler: ast.ExceptHandler,
                     helpers: Mapping[str, int] | None = None) -> str:
    helpers = helpers or {}
    raises = False
    level = 0
    for sub in ast.walk(ast.Module(body=handler.body, type_ignores=[])):
        if isinstance(sub, ast.Raise):
            raises = True
        elif isinstance(sub, ast.Call):
            level = max(level, _call_level(sub, helpers))
    if raises:
        return "raises"
    caught = _caught_names(handler)
    if level == 0 and caught and len(handler.body) == 1:
        only = handler.body[0]
        if caught <= _END_OF_DATA and isinstance(
                only, (ast.Break, ast.Continue, ast.Pass, ast.Return)):
            return "control-flow"
        if caught <= _END_OF_DATA | _POLL_TIMEOUT and isinstance(
                only, (ast.Break, ast.Continue)):
            return "control-flow"
    return _LEVEL_NAMES[level]


def _first_line(node: ast.AST, width: int = 72) -> str:
    try:
        text = ast.unparse(node).splitlines()[0]
    except Exception:  # noqa: BLE001 - a label only; never worth failing the map
        text = type(node).__name__
    return text if len(text) <= width else text[: width - 1] + "…"


# ── report ───────────────────────────────────────────────────────────────────

def cmd_report() -> int:
    try:
        import coverage
    except ImportError:
        print("coverage is not installed: venv\\Scripts\\python.exe -m pip "
              "install -r requirements-dev.txt")
        return 2
    if not DATA.exists() or not any(DATA.glob(".coverage.*")):
        print("no coverage data - run `tests\\coverage_map.py run` first")
        return 2
    os.chdir(REPO)      # the JSON report keys files relative to the cwd
    write_rc()
    combined = DATA / ".coverage"
    if combined.exists():
        combined.unlink()
    cov = coverage.Coverage(config_file=str(RC))
    cov.combine(data_paths=[str(DATA)], keep=True)
    cov.save()

    json_path = OUT / "coverage.json"
    cov.json_report(outfile=str(json_path), ignore_errors=True)
    branch_by_file: dict[str, dict[str, Any]] = {}
    for key, rec in json.loads(json_path.read_text(encoding="utf-8"))["files"].items():
        branch_by_file[os.path.normcase(str((REPO / key).resolve()))] = rec

    data = cov.get_data()
    stored = {os.path.normcase(f): f for f in data.measured_files()}

    parsed: list[tuple[str, Path, str, str, ast.AST]] = []
    for root in SOURCES:
        for path in sorted((REPO / root).rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            rel = path.relative_to(REPO).as_posix()
            src = path.read_text(encoding="utf-8", errors="replace")
            try:
                parsed.append((root, path, rel, src, ast.parse(src)))
            except SyntaxError as exc:
                print(f"  could not parse {rel}: {exc}")
    helpers = collect_log_helpers(tree for *_, tree in parsed)
    print(f"  logging helpers recognised: {sorted(helpers) or 'none'}")

    functions: list[dict[str, Any]] = []
    handlers: list[dict[str, Any]] = []
    files: list[dict[str, Any]] = []
    for root, path, rel, src, tree in parsed:
        try:
            _, statements, _excluded, missing, _ = cov.analysis2(str(path))
        except Exception as exc:  # noqa: BLE001 - reported, not hidden
            print(f"  could not analyse {rel}: {exc}")
            continue
        stmts, executed = set(statements), set(statements) - set(missing)
        norm = os.path.normcase(str(path))
        key = stored.get(norm)
        contexts = data.contexts_by_lineno(key) if key else {}
        brec = branch_by_file.get(norm, {})
        missing_br = [tuple(b) for b in brec.get("missing_branches", [])]
        taken_br = [tuple(b) for b in brec.get("executed_branches", [])]

        spans: list[tuple[int, int, str]] = []
        file_fns = []
        for node, qual, is_method in iter_functions(tree):
            spans.append((node.lineno, node.end_lineno or node.lineno, qual))
            file_fns.append(function_record(node, qual, is_method, rel, stmts,
                                            executed, contexts, missing_br,
                                            taken_br))
        functions.extend(file_fns)

        def enclosing(line: int) -> str:
            best = None
            for start, end, qual in spans:
                if start <= line <= end and (best is None or end - start < best[0]):
                    best = (end - start, qual)
            return best[1] if best else "<module>"

        for node in ast.walk(tree):
            if not isinstance(node, ast.ExceptHandler):
                continue
            first = node.body[0].lineno
            handlers.append({
                "file": rel, "line": node.lineno, "body_line": first,
                "in": enclosing(node.lineno),
                "catches": _first_line(node.type) if node.type else "(bare except)",
                "does": _first_line(node.body[0]),
                "kind": classify_handler(node, helpers),
                "reached": (first in executed) if first in stmts else None,
                "suites": sorted({(c or "(subprocess)")
                                  for c in contexts.get(first, [])}),
            })

        counted = [f for f in file_fns if f["status"] != "empty"]
        files.append({
            "file": rel, "root": root, "lines": src.count("\n"),
            "statements": len(stmts), "executed": len(executed),
            "functions": len(counted),
            "never": sum(f["status"] == "never" for f in counted),
            "partial": sum(f["status"] == "partial" for f in counted),
            "full": sum(f["status"] == "full" for f in counted),
            "branches": len(missing_br) + len(taken_br),
            "branches_missed": len(missing_br),
        })

    (OUT / "functions.json").write_text(json.dumps(functions, indent=1), encoding="utf-8")
    (OUT / "handlers.json").write_text(json.dumps(handlers, indent=1), encoding="utf-8")
    cov.html_report(directory=str(OUT / "html"), show_contexts=True,
                    skip_empty=True, title="Nova coverage map")
    report = render_report(files, functions, handlers, helpers)
    (OUT / "REPORT.md").write_text(report, encoding="utf-8")
    print(report.split("\n## ", 2)[1] if "\n## " in report else report)
    print(f"\nwritten: {OUT / 'REPORT.md'}\n         {OUT / 'html' / 'index.html'}")
    return 0


def _stamp() -> str:
    """When, at which commit, and whether the measured code had local edits."""
    now = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO,
                          capture_output=True, encoding="utf-8",
                          errors="replace").stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "--", *SOURCES], cwd=REPO,
                           capture_output=True, encoding="utf-8",
                           errors="replace").stdout.strip()
    return (f"Generated {now} at `{head}`"
            + (" (measured trees have uncommitted changes)" if dirty else ""))


def _pct(num: int, den: int) -> str:
    return f"{100.0 * num / den:.1f}%" if den else "—"


def render_report(files: list[dict], functions: list[dict], handlers: list[dict],
                  helpers: Mapping[str, int] | None = None) -> str:
    suites_path = OUT / "suites.json"
    suites = json.loads(suites_path.read_text(encoding="utf-8")) if suites_path.exists() else []
    passed = sum(s["status"] == "pass" for s in suites)
    minutes = sum(s["seconds"] for s in suites) / 60
    out: list[str] = [
        "# Coverage map: what no test runs",
        "",
        _stamp() + f" from {len(suites)} suites: {passed} passed under coverage, "
        f"{len(suites) - passed} did not; {minutes:.0f} min of suite time.",
        "",
        "A function is **run** when a statement of its own body executed in any "
        "suite (the `def` line runs at import and does not count). Run is not "
        "tested: this finds what nothing reaches. See `tests/coverage_map.py`.",
        "",
        "## Totals",
        "",
        "| tree | files | functions | never run | partly run | fully run "
        "| statements run | branches taken |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    groups = list(SOURCES) + ["focus: " + " + ".join(FOCUS), "everything"]
    for g in groups:
        if g == "everything":
            fs = files
        elif g.startswith("focus"):
            fs = [f for f in files if f["root"] in FOCUS]
        else:
            fs = [f for f in files if f["root"] == g]
        t = {k: sum(f[k] for f in fs) for k in ("functions", "never", "partial", "full",
                                                "statements", "executed", "branches",
                                                "branches_missed")}
        label = f"**{g}**" if g in ("everything",) or g.startswith("focus") else f"`{g}/`"
        out.append(
            f"| {label} | {len(fs)} | {t['functions']} | {t['never']} "
            f"({_pct(t['never'], t['functions'])}) | {t['partial']} | {t['full']} | "
            f"{_pct(t['executed'], t['statements'])} | "
            f"{_pct(t['branches'] - t['branches_missed'], t['branches'])} |")

    bad = [s for s in suites if s["status"] != "pass"]
    out += ["", "## Suites that did not pass under coverage", ""]
    if not bad:
        out.append("None - every suite passed while being measured.")
    for s in bad:
        out.append(f"- **{s['suite']}** — {s['status']} (exit {s['exit']}, {s['seconds']} s)")
        for ln in (s.get("output") or [])[-8:]:
            out.append(f"  - `{ln.strip()[:150]}`")

    routes = [f for f in functions if f["route"]]
    never_routes = [f for f in routes if f["status"] == "never"]
    out += ["", "## HTTP and WebSocket endpoints",
            "",
            f"{len(routes)} endpoints; **{len(never_routes)} are never called by any suite**"
            f" and {sum(f['status'] == 'partial' for f in routes)} only partly run.", ""]
    for f in sorted(never_routes, key=lambda r: (r["file"], r["line"])):
        out.append(f"- `{f['route']}` — `{f['file']}:{f['line']}` `{f['name']}`")

    focus_files = [f for f in files if f["root"] in FOCUS and f["functions"]]
    out += ["", "## Files with the most never-run functions (core, memory, backend)", "",
            "| file | functions | never | partly | statements run | branches taken |",
            "|---|---:|---:|---:|---:|---:|"]
    for f in sorted(focus_files, key=lambda r: (-r["never"], r["file"]))[:45]:
        if not f["never"]:
            break
        out.append(f"| `{f['file']}` | {f['functions']} | {f['never']} | {f['partial']} "
                   f"| {_pct(f['executed'], f['statements'])} "
                   f"| {_pct(f['branches'] - f['branches_missed'], f['branches'])} |")
    untouched = [f for f in focus_files if f["executed"] == 0]
    if untouched:
        out += ["", f"**{len(untouched)} files no suite executes a single line of:** "
                + ", ".join(f"`{f['file']}`" for f in sorted(untouched, key=lambda r: r["file"]))]

    kinds = ["quiet", "logs-debug", "logs-info", "logs-warning", "logs-error", "raises",
             "control-flow"]
    focus_h = [h for h in handlers if h["file"].split("/")[0] in FOCUS]
    out += ["", "## Error handlers (`except` blocks) in core, memory, backend", "",
            "| handler | count | reached by a suite | never reached |",
            "|---|---:|---:|---:|"]
    for k in kinds:
        hs = [h for h in focus_h if h["kind"] == k]
        out.append(f"| {k} | {len(hs)} | {sum(h['reached'] is True for h in hs)} "
                   f"| {sum(h['reached'] is False for h in hs)} |")
    out += ["",
            "*quiet* = neither re-raises nor logs nor prints. *logs-debug* is invisible at "
            "the default log level, so for a user it is as quiet as *quiet*. "
            "*control-flow* = catches only \"nothing more\" (empty queue, end of "
            "iteration) and simply exits, or a poll timeout and just loops again.", ""]
    if helpers:
        named = ", ".join(f"`{n}` ({_LEVEL_NAMES[lv].removeprefix('logs-')})"
                          for n, lv in sorted(helpers.items()))
        out += ["Functions whose whole job is to log, so a call to one counts as "
                f"logging at its level: {named}.", ""]
    swallowed = [h for h in focus_h if h["kind"] in ("quiet", "logs-debug") and h["reached"]]
    out += [f"### Quiet handlers that RAN during the suites ({len(swallowed)})", "",
            "Each of these swallowed an exception while a suite was running. Some are "
            "tests proving a guard works; any other one is a failure nobody heard.", ""]
    for h in sorted(swallowed, key=lambda r: (r["file"], r["line"])):
        who = ", ".join(h["suites"][:3]) + (" …" if len(h["suites"]) > 3 else "")
        out.append(f"- `{h['file']}:{h['line']}` in `{h['in']}` — except `{h['catches']}`"
                   f" → `{h['does']}` (by {who})")
    per_file = defaultdict(int)
    for h in focus_h:
        if h["kind"] in ("quiet", "logs-debug") and h["reached"] is False:
            per_file[h["file"]] += 1
    out += ["", "### Where the never-reached quiet handlers are", "",
            "| file | quiet handlers no suite reaches |", "|---|---:|"]
    for path, n in sorted(per_file.items(), key=lambda kv: (-kv[1], kv[0]))[:30]:
        out.append(f"| `{path}` | {n} |")

    out += ["", "## Every never-run function in core, memory, backend", "",
            "Public names first in each file. `functions.json` has every function, "
            "run or not, with the suites that reach it.", ""]
    by_file: dict[str, list[dict]] = defaultdict(list)
    for f in functions:
        if f["status"] == "never" and f["file"].split("/")[0] in FOCUS:
            by_file[f["file"]].append(f)
    for path in sorted(by_file):
        fs = sorted(by_file[path], key=lambda r: (r["private"], r["line"]))
        out.append(f"- **`{path}`** ({len(fs)}): " + ", ".join(
            f"`{r['name']}`:{r['line']}" for r in fs))
    out.append("")
    return "\n".join(out)


# ── swallowed: what did each quiet handler actually catch? ──────────────────
#
# Coverage can say a quiet `except` block ran; it cannot say WHAT it caught.
# A guard catching the malformed input its test fed it, and a KeyError from
# a real bug that every test has been walking past, look identical in the
# coverage data. The recorder tells them apart.

SWALLOW = OUT / "swallowed"           # recorder output: one .jsonl per process
HOOK_DIR = OUT / "swallow_hook"       # sitecustomize.py + targets.json

#: Installed as `sitecustomize` on PYTHONPATH, so it loads into every Python
#: process a suite starts - the restart suites' children included.
_HOOK_SRC = r'''"""Swallowed-exception recorder. Written by tests/coverage_map.py - edits are overwritten.

When the first line of a watched `except` block runs, this writes down the
exception being handled, where it was raised, which test function was on
the stack and which asyncio task was running. Each record is written the
moment it happens, so a process that dies by os._exit loses nothing.
"""
import json as _json
import os as _os
import sys as _sys
import threading as _threading

_LIMIT = 25          # records per (place, exception type) per process


def _install():
    targets_path = _os.environ.get("COVMAP_SWALLOW_TARGETS")
    out_dir = _os.environ.get("COVMAP_SWALLOW_OUT")
    if not targets_path or not out_dir:
        return
    with open(targets_path, encoding="utf-8") as fh:
        by_file = {_os.path.normcase(f): frozenset(v) for f, v in _json.load(fh).items()}
    suite = _os.environ.get("COVMAP_SWALLOW_SUITE", "?")
    tests_dir = _os.environ.get("COVMAP_SWALLOW_TESTS", "")
    tests_dir = _os.path.join(_os.path.normcase(tests_dir), "") if tests_dir else "\0"
    out_path = _os.path.join(out_dir, suite + "." + str(_os.getpid()) + ".jsonl")
    lock = _threading.Lock()
    seen = {}
    per_code = {}
    missing = object()
    failures = [0]

    def write(rec):
        line = _json.dumps(rec)
        with lock:
            with open(out_path, "a", encoding="utf-8") as fh:
                fh.write(line + "\n")

    def where(code, lineno):
        return code.co_filename + ":" + str(lineno) + " in " + code.co_name

    def record(frame):
        exc = _sys.exc_info()[1]
        name = (type(exc).__module__ + "." + type(exc).__qualname__) if exc is not None else None
        key = (frame.f_code, frame.f_lineno, name)
        with lock:
            n = seen.get(key, 0)
            if n >= _LIMIT:
                return
            seen[key] = n + 1
        try:
            msg = str(exc)[:300] if exc is not None else None
        except Exception:
            msg = "<str() failed>"
        origin = None
        tb = exc.__traceback__ if exc is not None else None
        while tb is not None and tb.tb_next is not None:
            tb = tb.tb_next
        if tb is not None:
            origin = where(tb.tb_frame.f_code, tb.tb_lineno)
        test = None
        f = frame.f_back
        while f is not None:
            fn = _os.path.normcase(f.f_code.co_filename)
            if (fn.startswith(tests_dir) and _os.path.basename(fn).startswith("test_")
                    and f.f_code.co_name != "<module>"):
                test = where(f.f_code, f.f_lineno)
                break
            f = f.f_back
        task = None
        aio = _sys.modules.get("asyncio")
        if aio is not None:
            try:
                t = aio.current_task()
                if t is not None:
                    task = t.get_name() + " " + getattr(t.get_coro(), "__qualname__", "?")
            except RuntimeError:
                pass        # no running loop in this thread
        write({"file": frame.f_code.co_filename, "line": frame.f_lineno, "suite": suite,
               "pid": _os.getpid(), "thread": _threading.current_thread().name,
               "exc": name, "msg": msg, "origin": origin, "test": test, "task": task})

    def local(frame, event, arg):
        if event == "line" and frame.f_lineno in per_code.get(frame.f_code, ()):
            try:
                record(frame)
            except Exception as exc:     # never raise into the code being observed
                failures[0] += 1
                if failures[0] == 1:
                    print("[coverage_map recorder] a record failed: " + repr(exc),
                          file=_sys.stderr)
        return local

    def global_(frame, event, arg):
        code = frame.f_code
        lines = per_code.get(code, missing)
        if lines is missing:
            lines = None
            wanted = by_file.get(_os.path.normcase(code.co_filename))
            if wanted:
                hit = wanted & {ln for _s, _e, ln in code.co_lines() if ln is not None}
                lines = frozenset(hit) or None
            per_code[code] = lines
        return local if lines else None

    write({"event": "loaded", "suite": suite, "pid": _os.getpid()})
    _sys.settrace(global_)
    _threading.settrace(global_)


try:
    _install()
except Exception as _exc:   # never break the process being observed - but say so
    print("[coverage_map recorder] not installed: " + repr(_exc), file=_sys.stderr)
'''


def write_swallow_hook(directory: Path, targets: Mapping[str, list[int]]) -> Path:
    """Write the recorder and its targets; returns the targets file."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "sitecustomize.py").write_text(_HOOK_SRC, encoding="utf-8")
    tpath = directory / "targets.json"
    tpath.write_text(json.dumps(dict(targets), indent=1), encoding="utf-8")
    return tpath


def recorder_env(base: Mapping[str, str], hook_dir: Path, targets: Path,
                 out_dir: Path, suite: str, tests_dir: Path) -> dict[str, str]:
    env = dict(base)
    env["PYTHONPATH"] = os.pathsep.join(
        [str(hook_dir)] + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else []))
    env["COVMAP_SWALLOW_TARGETS"] = str(targets)
    env["COVMAP_SWALLOW_OUT"] = str(out_dir)
    env["COVMAP_SWALLOW_SUITE"] = suite
    env["COVMAP_SWALLOW_TESTS"] = str(tests_dir)
    return env


def swallow_targets(handlers: list[dict], repo: Path = REPO) -> dict[str, list[int]]:
    """The first body line of every quiet or debug-only handler, by absolute file."""
    out: dict[str, set[int]] = defaultdict(set)
    for h in handlers:
        if h["kind"] in ("quiet", "logs-debug") and h.get("body_line"):
            out[str(repo / h["file"])].add(h["body_line"])
    return {f: sorted(v) for f, v in sorted(out.items())}


def read_swallow_records(directory: Path) -> list[dict]:
    recs: list[dict] = []
    for p in sorted(directory.glob("*.jsonl")):
        for ln in p.read_text(encoding="utf-8", errors="replace").splitlines():
            if not ln.strip():
                continue
            try:
                recs.append(json.loads(ln))
            except json.JSONDecodeError:
                # A torn line is reported, never dropped without a word.
                print(f"  unreadable record in {p.name}: {ln[:80]}")
    return recs


def _norm(repo: Path, file: str) -> str:
    return os.path.normcase(os.path.normpath(os.path.join(str(repo), file)))


def aggregate_swallowed(records: Iterable[dict], handlers: list[dict],
                        repo: Path = REPO) -> tuple[list[dict], int]:
    """Group recorder hits by handler, then by the exception type it caught.

    Returns (groups, hits that matched no known handler). Records are keyed
    by the handler's first BODY line, which is what the recorder watches.
    """
    index = {(_norm(repo, h["file"]), h["body_line"]): h
             for h in handlers if h.get("body_line")}
    groups: dict[tuple[str, int], dict] = {}
    unmatched = 0
    for r in records:
        if r.get("event") == "loaded":
            continue
        key = (_norm(repo, r["file"]), r["line"])
        h = index.get(key)
        if h is None:
            unmatched += 1
            continue
        g = groups.setdefault(key, {
            **{k: h[k] for k in ("file", "line", "in", "catches", "does", "kind")},
            "caught": {}})
        exc = r.get("exc") or "(nothing being handled)"
        c = g["caught"].setdefault(exc, {"exc": exc, "hits": 0, "messages": [],
                                         "origins": [], "suites": set(),
                                         "tests": set(), "tasks": set()})
        c["hits"] += 1
        for field, value in (("messages", r.get("msg")), ("origins", r.get("origin"))):
            if value and value not in c[field] and len(c[field]) < 3:
                c[field].append(value)
        c["suites"].add(r.get("suite") or "?")
        for field, value in (("tests", r.get("test")), ("tasks", r.get("task"))):
            if value:
                c[field].add(value)
    out = []
    for key in sorted(groups, key=lambda k: (groups[k]["file"], groups[k]["line"])):
        g = groups[key]
        g["caught"] = [{**c, "suites": sorted(c["suites"]), "tests": sorted(c["tests"]),
                        "tasks": sorted(c["tasks"])}
                       for c in sorted(g["caught"].values(), key=lambda c: -c["hits"])]
        out.append(g)
    return out, unmatched


def _short(path: str | None) -> str:
    """A recorded absolute location, relative to the repo where it can be."""
    if not path:
        return "?"
    prefix = str(REPO) + os.sep
    return path[len(prefix):].replace(os.sep, "/") if path.startswith(prefix) else path


def render_swallowed(groups: list[dict], unmatched: int, handlers: list[dict],
                     suites: list[dict], processes: int) -> str:
    watched = [h for h in handlers if h["kind"] in ("quiet", "logs-debug")
               and h.get("body_line")]
    seen = {(g["file"], g["line"]) for g in groups}
    missed = [h for h in watched if h["reached"] and (h["file"], h["line"]) not in seen]
    bad = [s for s in suites if s["status"] != "pass"]
    out = ["# What the quiet handlers caught", "",
           _stamp() + f". {len(suites)} suites run with the recorder "
           f"({len(bad)} did not pass), {processes} Python processes recorded.", "",
           f"{len(watched)} quiet or debug-only `except` blocks watched; "
           f"**{len(groups)} caught something.** Each entry is one block, then "
           "every exception type it caught: how often, an example message, where "
           "it was raised, and the test function on the stack (none when the "
           "block ran in a background task - the task is named instead).", ""]
    if unmatched:
        out += [f"{unmatched} recorded hits matched no handler in `handlers.json` - "
                "the source changed since `report`; re-run it.", ""]
    for s in bad:
        out.append(f"- suite **{s['status']}**: `{s['suite']}`")
    if bad:
        out.append("")
    for g in groups:
        out += [f"### `{g['file']}:{g['line']}` in `{g['in']}`", "",
                f"except `{g['catches']}` → `{g['does']}` *({g['kind']})*", ""]
        for c in g["caught"]:
            msg = (c["messages"][0] if c["messages"] else "").replace("\n", " ")
            out.append(f"- **`{c['exc']}`** ×{c['hits']} — e.g. \"{msg[:160]}\"")
            out.append("  - raised at " + "; ".join(f"`{_short(o)}`" for o in c["origins"]))
            who = ", ".join(c["suites"][:4]) + (" …" if len(c["suites"]) > 4 else "")
            out.append(f"  - suites: {who}")
            if c["tests"]:
                out.append("  - test on the stack: " + "; ".join(
                    f"`{_short(t)}`" for t in c["tests"][:3]))
            if c["tasks"]:
                out.append("  - task: " + "; ".join(f"`{t}`" for t in c["tasks"][:3]))
        out.append("")
    if missed:
        out += ["## Reached under coverage, never seen by the recorder", "",
                "Coverage says these ran, but no recorded process saw them: a "
                "process the recorder did not load into, or a run that differs "
                "from the coverage run. Each one is unexplained until checked.", ""]
        out += [f"- `{h['file']}:{h['line']}` in `{h['in']}` (by "
                + ", ".join(h["suites"][:3]) + ")" for h in missed]
        out.append("")
    return "\n".join(out)


def cmd_swallowed(pattern: str | None) -> int:
    hpath = OUT / "handlers.json"
    if not hpath.exists():
        print("no handler map - run `tests\\coverage_map.py report` first")
        return 2
    handlers = json.loads(hpath.read_text(encoding="utf-8"))
    if not any("body_line" in h for h in handlers):
        print("handlers.json predates the recorder - re-run `report`")
        return 2
    suites = sorted((REPO / "tests").glob("test_*.py"))
    if pattern:
        rx = re.compile(pattern)
        suites = [s for s in suites if rx.search(s.name)]
    else:
        # Only suites that coverage saw reach a watched block can hit one.
        wanted = {s for h in handlers if h["kind"] in ("quiet", "logs-debug")
                  and h["reached"] for s in h["suites"]}
        if "(subprocess)" in wanted:
            print("  a watched block was reached only by an unlabelled child "
                  "process - running every suite")
        else:
            suites = [s for s in suites if s.stem in wanted]
    if not suites:
        print("no suites to run")
        return 2

    if SWALLOW.exists():
        shutil.rmtree(SWALLOW)
    SWALLOW.mkdir(parents=True)
    targets = write_swallow_hook(HOOK_DIR, swallow_targets(handlers))
    base = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONPATH=str(REPO),
                NOVA_IT_WATCHDOG_S=str(SUITE_TIMEOUT_S))
    results: list[dict[str, Any]] = []
    t_all = time.perf_counter()
    for i, suite in enumerate(suites, 1):
        env = recorder_env(base, HOOK_DIR, targets, SWALLOW, suite.stem, REPO / "tests")
        t0 = time.perf_counter()
        try:
            proc = subprocess.run([str(PY), str(suite)], cwd=REPO, env=env,
                                  capture_output=True, encoding="utf-8",
                                  errors="replace", timeout=SUITE_TIMEOUT_S + 60)
            code: int | None = proc.returncode
            out = _text(proc.stdout) + _text(proc.stderr)
        except subprocess.TimeoutExpired as exc:
            code = None
            out = _text(exc.stdout) + _text(exc.stderr)
        elapsed = time.perf_counter() - t0
        status = "pass" if code == 0 else ("timeout" if code is None else "fail")
        rec: dict[str, Any] = {"suite": suite.name, "status": status, "exit": code,
                               "seconds": round(elapsed, 1)}
        if "[coverage_map recorder]" in out:
            rec["recorder"] = [ln for ln in out.splitlines()
                               if "[coverage_map recorder]" in ln][:5]
        if status != "pass":
            rec["output"] = out.splitlines()[-40:]
        results.append(rec)
        (OUT / "swallowed_suites.json").write_text(json.dumps(results, indent=1),
                                                    encoding="utf-8")
        print(f"[{i:3}/{len(suites)}] {status:7} {elapsed:7.1f}s  {suite.name}"
              + ("  RECORDER: " + rec["recorder"][0] if "recorder" in rec else ""),
              flush=True)

    records = read_swallow_records(SWALLOW)
    processes = sum(1 for r in records if r.get("event") == "loaded")
    groups, unmatched = aggregate_swallowed(records, handlers)
    (OUT / "swallowed.json").write_text(json.dumps(groups, indent=1), encoding="utf-8")
    (OUT / "SWALLOWED.md").write_text(
        render_swallowed(groups, unmatched, handlers, results, processes),
        encoding="utf-8")
    bad = [r for r in results if r["status"] != "pass"]
    print(f"\n{len(results) - len(bad)}/{len(results)} suites passed with the "
          f"recorder in {(time.perf_counter() - t_all) / 60:.1f} min; "
          f"{processes} processes recorded; {len(groups)} quiet blocks caught "
          f"something\nwritten: {OUT / 'SWALLOWED.md'}")
    return 1 if bad else 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run", help="run the suites under coverage")
    r.add_argument("pattern", nargs="?", help="regex on suite file names")
    r.add_argument("--append", action="store_true",
                   help="add to the previous run's data instead of starting over")
    sub.add_parser("report", help="map the measured data onto functions")
    s = sub.add_parser("swallowed", help="re-run the suites that reach quiet except "
                       "blocks, recording what each one caught")
    s.add_argument("pattern", nargs="?", help="regex on suite file names "
                   "(default: every suite that reached a quiet block)")
    args = ap.parse_args(argv)
    if args.cmd == "run":
        return cmd_run(args.pattern, args.append)
    if args.cmd == "swallowed":
        return cmd_swallowed(args.pattern)
    return cmd_report()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
