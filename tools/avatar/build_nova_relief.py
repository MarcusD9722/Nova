def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete()
    for block in (bpy.data.meshes, bpy.data.materials, bpy.data.images, bpy.data.actions, bpy.data.curves):
        for item in list(block):
            if item.users == 0:
                block.remove(item)


def make_material(name, base=PURPLE, emission=None, strength=1.0, alpha=1.0, rough=0.4, metal=0.05):
    mat = bpy.data.materials.new(name)
    try:
        mat.use_nodes = True
    except Exception:
        pass
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = base
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Metallic"].default_value = metal
    bsdf.inputs["Alpha"].default_value = alpha
    if emission is not None:
        bsdf.inputs["Emission Color"].default_value = emission
        bsdf.inputs["Emission Strength"].default_value = strength
    if alpha < 1.0:
        for attr, value in (("blend_method", "BLEND"), ("surface_render_method", "BLENDED")):
            try:
                setattr(mat, attr, value)
            except Exception:
                pass
    return mat


def new_empty(name, parent=None, location=(0, 0, 0)):
    empty = bpy.data.objects.new(name, None)
    empty.location = location
    bpy.context.collection.objects.link(empty)
    if parent is not None:
        empty.parent = parent
    return empty


def stash_clip(owner, action, clip_name, start=1):
    ad = owner.animation_data or owner.animation_data_create()
    ad.action = None
    track = ad.nla_tracks.new()
    track.name = clip_name
    strip = track.strips.new(action.name, int(start), action)
    strip.name = clip_name
    return strip


def animate_object(obj, clip_name, keys):
    ad = obj.animation_data or obj.animation_data_create()
    action = bpy.data.actions.new(f"{clip_name}_{obj.name}")
    ad.action = action
    try:
        if ad.action_slot is None and action.slots:
            ad.action_slot = action.slots[0]
    except Exception:
        pass
    for frame, values in keys:
        for path, value in values.items():
            setattr(obj, path, value)
            obj.keyframe_insert(data_path=path, frame=frame)
    stash_clip(obj, action, clip_name)


def animate_shape_keys(mesh_obj, clip_name, keys):
    shape_keys = mesh_obj.data.shape_keys
    ad = shape_keys.animation_data or shape_keys.animation_data_create()
    action = bpy.data.actions.new(f"{clip_name}_keys")
    ad.action = action
    try:
        if ad.action_slot is None and action.slots:
            ad.action_slot = action.slots[0]
    except Exception:
        pass
    names = set()
    for _, values in keys:
        names.update(values.keys())
    for frame, values in keys:
        for name in names:
            kb = shape_keys.key_blocks.get(name)
            if kb is None:
                continue
            kb.value = values.get(name, kb.value if frame > 1 else 0.0)
            kb.keyframe_insert(data_path="value", frame=frame)
    for name in names:
        kb = shape_keys.key_blocks.get(name)
        if kb is not None:
            kb.value = 0.0
    stash_clip(shape_keys, action, clip_name)


def load_pixels(path):
    img = bpy.data.images.load(path)
    w, h = img.size
    arr = np.array(img.pixels[:], dtype=np.float32).reshape(h, w, 4)  # bottom-up rows
    return img, arr, w, h


def sample(arr, u, v):
    """Bilinear-ish (nearest is fine at our density) sample, uv in [0,1]."""
    h, w = arr.shape[0], arr.shape[1]
    x = min(w - 1, max(0, int(round(u * (w - 1)))))
    y = min(h - 1, max(0, int(round(v * (h - 1)))))
    return arr[y, x]


