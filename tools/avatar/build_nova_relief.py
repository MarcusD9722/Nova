def region_key(name, center_u, center_v, ru, rv, move, domain=None):
    """Add a shape key displacing verts inside an ellipse with smooth falloff.

    move(weight, u, v) -> (dx, dy, dz); domain(vi, u, v) -> bool limits which
    vertices may move (used to keep the upper lip still while the jaw opens).
    """
    kb = face_obj.shape_key_add(name=name, from_mix=False)
    for vi, vert in enumerate(mesh.vertices):
        u, v = uv_of[vi]
        if domain is not None and not domain(vi, u, v):
            continue
        du, dv = (u - center_u) / ru, (v - center_v) / rv
        dist2 = du * du + dv * dv
        if dist2 >= 1.0:
            continue
        weight = (1.0 - dist2) ** 1.5
        dx, dy, dz = move(weight, u, v)
        co = vert.co
        kb.data[vi].co = (co.x + dx, co.y + dy, co.z + dz)
    return kb


def _lower_jaw_domain(vi, u, v):
    """Lower lip + chin only: seam duplicates and everything below the seam."""
    return vi in dup_set or v < LIP_V - 1e-6


